#!/usr/bin/env python3
"""Generate docs/WALKTHROUGH.md from a real conversation pair and real model output.

Written as a script rather than by hand so the document cannot drift from the code.
Re-run it after any change to the generator, the templates or the schema.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from taskswitch.generator import build_pair
from taskswitch.ops import TaskKind
from taskswitch.runner import ACK, build_messages, resolve_model, run_conversation
from taskswitch.scorer import score

SEED, TASKS = 1001, [TaskKind.SHOPPING, TaskKind.SCHEDULE]
MODEL = sys.argv[1] if len(sys.argv) > 1 else "qwen2.5-coder:7b"


def fmt_ops(conv):
    return "\n".join(
        f"  {i:>2}. {o.task.value:<9} {o.kind.value:<13} {json.dumps(o.payload)}"
        for i, o in enumerate(conv.ops))


def main() -> None:
    blocked, inter = build_pair(SEED, TASKS, n_ops=6, n_false=2, n_noise=2)
    model = resolve_model(MODEL)
    rb, ri = (run_conversation(c, model) for c in (blocked, inter))
    sb, si = score(rb), score(ri)

    out = f"""# Walkthrough: one conversation, end to end

Generated by `tools/make_walkthrough.py` from seed {SEED}, so it cannot drift from the
code. Re-run it after any change to the generator or the schema.

    python tools/make_walkthrough.py {MODEL}

---

## 1. The operation sample

`sample_ops(seed={SEED}, tasks=[shopping, schedule], n_ops=6, n_false=2, n_noise=2)`
emits a flat list of `Op` objects. This *same list* goes to two places: the renderer,
which turns it into user turns, and the oracle, which computes the answer key.

```
{fmt_ops(blocked)}
```

Note ops of kind `noise` and `false_assert`. Neither advances state — `noise` is
topical padding and the length lever, `false_assert` is a counterfactual the model must
*not* act on.

## 2. The two orderings

Same operations, same rendered strings, different sequence.

**Blocked** — task order `{' '.join(o.task.value[:4] for o in blocked.ops)}`

```
{chr(10).join(f'  user: {t}' for t in blocked.turns)}
  user: {blocked.final_request}
```

**Interleaved** — task order `{' '.join(o.task.value[:4] for o in inter.ops)}`

```
{chr(10).join(f'  user: {t}' for t in inter.turns)}
  user: {inter.final_request}
```

Between every pair of user turns the harness inserts a **prefilled** assistant turn,
`"{ACK}"`, which the model never generated. That is what makes the two prompts the
identical multiset of strings, and therefore identical in length.

## 3. The ground truth

`state.ground_truth(ops, tasks)` applies the same list to a plain state machine:

```json
{json.dumps(blocked.expected, indent=2)}
```

Both orderings produce this same answer key — asserted, not assumed
(`test_ordering_does_not_change_ground_truth`).

## 4. What the model returned

Model: `{model.name}` (digest `{model.digest or '?'}`), greedy, schema-constrained on
the final turn only.

| | blocked | interleaved |
|---|---|---|
| prompt tokens | {rb.prompt_tokens} | {ri.prompt_tokens} |
| turns | {len(blocked.turns)} | {len(inter.turns)} |
| messages sent | {len(build_messages(blocked))} | {len(build_messages(inter))} |
| parsed OK | {rb.parse_ok} | {ri.parse_ok} |

**Token delta: {abs(rb.prompt_tokens - ri.prompt_tokens)}.** This is the token match,
verified against Ollama's own count rather than estimated.

Blocked response:
```json
{json.dumps(rb.parsed.model_dump() if rb.parsed else None, indent=2)}
```

Interleaved response:
```json
{json.dumps(ri.parsed.model_dump() if ri.parsed else None, indent=2)}
```

## 5. The score

Grading is a dict comparison, so there is nothing to argue about.

| | blocked | interleaved |
|---|---|---|
| joint correct | {sb.joint_correct} | {si.joint_correct} |
| per task | {sb.per_task_correct} | {si.per_task_correct} |
| failures | {sb.failure_kinds or '[]'} | {si.failure_kinds or '[]'} |

Blocked detail: `{sb.failures or '[]'}`

Interleaved detail: `{si.failures or '[]'}`

---

## Reading a failure

Each entry is `(bucket, "task:identity detail")`:

- `dropped` — the operation never landed anywhere
- `misattributed` — it landed in the *other* task's state
- `absorbed … false_assert` — a planted counterfactual entered state
- `absorbed … hallucination` — content that was never mentioned at all entered state
- `dropped … wrong value` — the entity is present but its value is wrong (a meeting at
  the wrong hour). Counted once, not as a disappearance plus an invention.
"""
    Path("docs/WALKTHROUGH.md").write_text(out)
    print("wrote docs/WALKTHROUGH.md")
    print(f"  token delta {abs(rb.prompt_tokens - ri.prompt_tokens)}  "
          f"blocked joint={sb.joint_correct} interleaved joint={si.joint_correct}")


if __name__ == "__main__":
    main()
